import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const RAW_DIR = "raw/projects";
const OUT_DIR = "public/images/projects";
const MANIFEST = "src/views/data/projects.images.js";
const WIDTHS = [640, 1024, 1600];
const AVIF = { quality: 62, effort: 6, chromaSubsampling: "4:4:4" };

const only = process.argv[2];
const manifest = existsSync(MANIFEST)
  ? JSON.parse(
      (await readFile(MANIFEST, "utf8")).replace(/^[^{]*/, "").replace(/;\s*$/, ""),
    )
  : {};

const projectDirs = (await readdir(RAW_DIR, { withFileTypes: true }))
  .filter((d) => d.isDirectory() && (!only || d.name === only))
  .map((d) => d.name);

for (const id of projectDirs) {
  const files = (await readdir(path.join(RAW_DIR, id))).filter((f) =>
    /\.(png|jpe?g|webp)$/i.test(f),
  );
  if (files.length === 0) continue;
  await mkdir(path.join(OUT_DIR, id), { recursive: true });

  for (const file of files) {
    const name = file.replace(/\.[^.]+$/, "");
    const src = path.join(RAW_DIR, id, file);
    const meta = await sharp(src).metadata();
    const widths = WIDTHS.filter((w) => w <= meta.width);
    if (widths.length === 0 || widths.at(-1) < meta.width) {
      widths.push(Math.min(meta.width, WIDTHS.at(-1)));
    }
    const sizes = [...new Set(widths)];

    let kbTotal = 0;
    for (const w of sizes) {
      const out = path.join(OUT_DIR, id, `${name}-${w}.avif`);
      const info = await sharp(src).resize({ width: w }).avif(AVIF).toFile(out);
      kbTotal += info.size / 1024;
    }

    manifest[`${id}/${name}`] = {
      width: meta.width,
      height: meta.height,
      sizes,
    };
    console.log(
      `  ${id}/${name}`.padEnd(52),
      `${meta.width}x${meta.height}`.padEnd(12),
      `-> ${sizes.join("/")}`.padEnd(20),
      `${kbTotal.toFixed(0)}KB total`,
    );
  }
}

const sorted = Object.fromEntries(
  Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)),
);
await writeFile(
  MANIFEST,
  "// Generated by scripts/make-project-images.mjs — do not edit by hand.\n" +
    `export default ${JSON.stringify(sorted, null, 2)};\n`,
);
console.log(`\n  manifest: ${MANIFEST} (${Object.keys(sorted).length} images)`);
