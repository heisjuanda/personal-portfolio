import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

import { BASE_URL, SEO_ROUTES } from "../src/routes.seo.js";

function gitDate(...paths) {
  try {
    const args = ["log", "-1", "--format=%cI"];
    if (paths.length) args.push("--", ...paths);
    const out = execFileSync("git", args, { encoding: "utf8" }).trim();
    if (out) return out;
  } catch {
    // no git history available (shallow CI clone, tarball, etc.)
  }
  return new Date().toISOString();
}

const repoDate = gitDate();

const entries = Object.entries(SEO_ROUTES)
  .map(([path, seo]) => ({
    loc: path === "/" ? `${BASE_URL}/` : `${BASE_URL}${path}`,
    lastmod: (seo.lastmod ?? repoDate).slice(0, 10),
    images: seo.images ?? [],
  }))
  .sort((a, b) => a.loc.localeCompare(b.loc));

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${entries
  .map(
    (e) => `
  <url>
    <loc>${e.loc}</loc>
    <lastmod>${e.lastmod}</lastmod>${e.images
      .map((src) => `
    <image:image>
      <image:loc>${src}</image:loc>
    </image:image>`)
      .join("")}
  </url>
`,
  )
  .join("")}
</urlset>
`;

writeFileSync("public/sitemap.xml", sitemap, "utf8");

writeFileSync(
  "src/build-info.js",
  `// Generated by scripts/generate-seo-dates.mjs — do not edit by hand.\n` +
    `export const LAST_MODIFIED = "${repoDate}";\n`,
  "utf8",
);

console.log(`  stamp: ${repoDate}`);
console.log(`  sitemap.xml: ${entries.length} URLs`);
for (const e of entries) {
  console.log(
    `    ${e.lastmod}  ${(e.loc.replace(BASE_URL, "") || "/").padEnd(28)} ${e.images.length} images`,
  );
}
